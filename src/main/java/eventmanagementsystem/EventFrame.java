    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        dtm=(DefaultTableModel)jTable1.getModel();
        
        if(jTable1.getSelectedRowCount()==1)
        {
            int i = jTable1.getSelectedRow();
            int b = JOptionPane.showConfirmDialog(this, "Do you want to delete this row?","Delete",JOptionPane.YES_NO_OPTION,3);
            if(b == 0)
            {
                dtm.removeRow(i);
                eventList.remove(i);
            }
            else
            {
                JOptionPane.showMessageDialog(this, "Thank You!");
            }
        }
        else
        {
            JOptionPane.showMessageDialog(this,"Select 1 Row");
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String id = jTextField1.getText();
        String catagory = jTextField4.getText();
        String eventName = jTextField3.getText();
        String eventDate = ((JTextField)jDateChooser1.getDateEditor().getUiComponent()).getText();
        String location = jComboBox1.getSelectedItem().toString();
        String duration = jTextField5.getText();
        
        for (EventBooking e : eventList)
{
    if (e.id.equals(id))
    {
        JOptionPane.showMessageDialog(this, "This Event ID already exists.");
        return;
    }
    if (e.eventDate.equals(eventDate) && e.location.equals(location))
    {
        JOptionPane.showMessageDialog(this, "This location is already booked on this date.");
        return;
    }
}
        eventList.add(new EventBooking(id, catagory, eventName, eventDate, duration, location));
        dtm=(DefaultTableModel)jTable1.getModel();
        dtm.setRowCount(0);
        Object a[]=new Object[6];
        
        for(EventBooking m:eventList)
        {
            a[0] = m.id;
            a[1] = m.catagory;
            a[2] = m.eventName;
            a[3] = m.eventDate;
            a[4] = m.location;
            a[5] = m.duration;
            dtm.addRow(a);
        }
        jTextField1.setText("");
        jTextField4.setText("");
        jTextField3.setText("");
        jDateChooser1.setCalendar(null);
        jComboBox1.setSelectedIndex(0);
        jTextField5.setText("");
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        dtm = (DefaultTableModel)jTable1.getModel();
        String id = jTextField1.getText();
        String catagory = jTextField4.getText();
        String eventName = jTextField3.getText();
        String eventDate = ((JTextField)jDateChooser1.getDateEditor().getUiComponent()).getText();
        String location = jComboBox1.getSelectedItem().toString();
        String duration = jTextField5.getText();
        
        eventDate = ((JTextField)jDateChooser1.getDateEditor().getUiComponent()).getText();
        int i = jTable1.getSelectedRow();
        if (i == -1)
{
    JOptionPane.showMessageDialog(this, "Select a row first.");
    return;
}
for (int k = 0; k < eventList.size(); k++)
{
    if (k == i) continue;
    EventBooking e = eventList.get(k);
    if (e.id.equals(id))
    {
        JOptionPane.showMessageDialog(this, "This Event ID already exists.");
        return;
    }
    if (e.eventDate.equals(eventDate) && e.location.equals(location))
    {
        JOptionPane.showMessageDialog(this, "This location is already booked on this date.");
        return;
    }
}
        eventList.get(i).id = id;
        eventList.get(i).catagory = catagory;
        eventList.get(i).eventName = eventName;
        eventList.get(i).eventDate = eventDate;
        eventList.get(i).location = location;
        eventList.get(i).duration = duration;
        dtm.setValueAt(id, i,0);
        dtm.setValueAt(catagory, i, 1);
        dtm.setValueAt(eventName, i, 2);
        dtm.setValueAt(eventDate, i, 3);
        dtm.setValueAt(location, i, 4);
        dtm.setValueAt(duration, i, 5); 
        
        jTextField1.setText("");
        jTextField4.setText("");
        jTextField3.setText("");
        jDateChooser1.setCalendar(null);
        jComboBox1.setSelectedIndex(0);
        jTextField5.setText("");
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        try
        {
            int i = jTable1.getSelectedRow();
            String a = dtm.getValueAt(i, 0).toString();
            String b = dtm.getValueAt(i, 1).toString();
            String c = dtm.getValueAt(i, 2).toString();
            String d = dtm.getValueAt(i, 3).toString();
            String e = dtm.getValueAt(i, 4).toString();
            String f = dtm.getValueAt(i, 5).toString();
            jTextField1.setText(a);
            jTextField4.setText(b);
            jTextField3.setText(c);
            Date s = new SimpleDateFormat("d MMM, y").parse((String)d.toString());
            jDateChooser1.setDate(s);
            jComboBox1.setSelectedItem(e);
            jTextField5.setText(f);
            
        }
        catch(Exception e)
        {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jTable1MouseClicked

